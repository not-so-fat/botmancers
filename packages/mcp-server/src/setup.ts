// `botmancers setup`: create BOTMANCERS_HOME owner-only and generate the two
// local credentials the supervised product needs:
//
//   - the bridge-to-core service token: raw in config/bridge.env (the bridge
//     sends it), only its SHA-256 digest in config/core.env as
//     BOTMANCERS_SERVICE_TOKENS (what the engine reads);
//   - the inbound MCP bearer token MCP clients send to the bridge, in
//     config/bridge.env.
//
// Setup never writes Hermes or coding-agent credentials; it prints where
// the operator adds them. Re-running keeps existing tokens and re-tightens
// permissions; lines the operator added to core.env survive.
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { DEFAULT_PORT, ENV, MIN_MCP_TOKEN_LENGTH } from './config.js';
import { HOME_DIRS, PRODUCT_HOST, type HomePaths, ensurePrivateDir, readEnvFile, writePrivateFile } from './home.js';

export const BRIDGE_SERVICE_ID = 'botmancers-bridge';
export const SERVICE_TOKENS_ENV = 'BOTMANCERS_SERVICE_TOKENS';

export function serviceTokenDigest(token: string): string {
  return `sha256:${createHash('sha256').update(token, 'utf8').digest('hex')}`;
}

export function generateToken(prefix: string): string {
  return `${prefix}_${randomBytes(32).toString('hex')}`;
}

export interface SetupState {
  ok: boolean;
  problems: string[];
}

// Whether config/core.env and config/bridge.env hold a consistent pair.
export function credentialState(paths: HomePaths): SetupState {
  const problems: string[] = [];
  const bridge = readEnvFile(paths.bridgeEnv);
  const core = readEnvFile(paths.coreEnv);
  if (!bridge) problems.push(`${paths.bridgeEnv} is missing`);
  if (!core) problems.push(`${paths.coreEnv} is missing`);
  if (bridge && core) {
    const service = bridge[ENV.serviceToken] ?? '';
    const mcp = bridge[ENV.mcpToken] ?? '';
    if (!service) problems.push(`${ENV.serviceToken} is missing from bridge.env`);
    if (mcp.length < MIN_MCP_TOKEN_LENGTH) problems.push(`${ENV.mcpToken} is missing or too short in bridge.env`);
    if (service && mcp === service) problems.push('the MCP token must differ from the service token');
    const listed = (core[SERVICE_TOKENS_ENV] ?? '').split(/[,\s]+/).filter(Boolean);
    if (service && !listed.includes(`${BRIDGE_SERVICE_ID}=${serviceTokenDigest(service)}`)) {
      problems.push(`core.env ${SERVICE_TOKENS_ENV} does not list the digest of the bridge service token`);
    }
    if (Object.values(core).some(value => value === service || value === mcp)) problems.push('core.env contains a raw bridge token');
  }
  return { ok: problems.length === 0, problems };
}

// Replace (or append) one KEY=value line, keeping every other line.
function upsertLine(text: string, key: string, value: string): string {
  const line = `${key}=${value}`;
  const pattern = new RegExp(`^\\s*(?:export\\s+)?${key}=.*$`, 'm');
  if (pattern.test(text)) return text.replace(pattern, line);
  return `${text.replace(/\n*$/, '\n')}${line}\n`;
}

const CORE_HEADER = `# Botmancers core engine configuration (generated by \`botmancers setup\`).
# Read by \`botmancers start\`; variables exported in your shell take precedence,
# except ${SERVICE_TOKENS_ENV}, which pairs with config/bridge.env.
#
# ${SERVICE_TOKENS_ENV} holds only the SHA-256 digest of the bridge's service
# token; the raw token is in bridge.env.
#
# Hermes (conversational turns): add your gateway key here, e.g.
#   HERMES_API_SERVER_KEY=<key from your Hermes gateway>
#   HERMES_BASE_URL=http://127.0.0.1:8642
# Coding-agent runs need no token here: install the provider CLIs
# (claude, codex, cursor, muse) and sign each one in.
# MCP coordinators reachable through botmancers_start_task (Agent names):
#   BOTMANCERS_MCP_COORDINATORS=Tank
`;

const BRIDGE_HEADER = `# Botmancers MCP bridge credentials (generated by \`botmancers setup\`). Keep private.
# ${ENV.serviceToken}: what the bridge sends to the core engine (core.env holds its digest).
# ${ENV.mcpToken}: what MCP clients send to the bridge as Authorization: Bearer <token>.
`;

export interface SetupResult {
  created: boolean;
  lines: string[];
}

export class SetupError extends Error {}

export function runSetup(paths: HomePaths, ports: { ui: number; mcp: number }): SetupResult {
  try {
    ensurePrivateDir(paths.home);
    for (const dir of HOME_DIRS) ensurePrivateDir(`${paths.home}/${dir}`);

    let created = false;
    if (!credentialState(paths).ok) {
      const serviceToken = generateToken('bmsvc');
      const mcpToken = generateToken('bmmcp');
      const existingCore = existsSync(paths.coreEnv) ? readFileSync(paths.coreEnv, 'utf8') : CORE_HEADER;
      writePrivateFile(paths.coreEnv, upsertLine(existingCore, SERVICE_TOKENS_ENV, `${BRIDGE_SERVICE_ID}=${serviceTokenDigest(serviceToken)}`));
      writePrivateFile(paths.bridgeEnv, `${BRIDGE_HEADER}${ENV.serviceToken}=${serviceToken}\n${ENV.mcpToken}=${mcpToken}\n`);
      created = true;
    } else {
      // Re-tighten in case permissions were loosened.
      writePrivateFile(paths.coreEnv, readFileSync(paths.coreEnv, 'utf8'));
      writePrivateFile(paths.bridgeEnv, readFileSync(paths.bridgeEnv, 'utf8'));
    }

    const ui = `http://${PRODUCT_HOST}:${ports.ui}`;
    const mcp = `http://${PRODUCT_HOST}:${ports.mcp}/mcp`;
    const lines = [
      created
        ? `botmancers setup: initialized ${paths.home} (owner-only) and generated the bridge credentials.`
        : `botmancers setup: ${paths.home} is already set up; kept the existing credentials and re-checked permissions.`,
      `  ${paths.coreEnv}    core engine configuration (service-token digest only)`,
      `  ${paths.bridgeEnv}  MCP bridge credentials (keep private)`,
      '',
      'Start Botmancers (UI, API, core engine, and MCP bridge):',
      '  botmancers start --daemon --open',
      `  UI ${ui}   MCP ${mcp}${ports.mcp === DEFAULT_PORT ? '' : ` (port ${ports.mcp})`}`,
      '',
      'MCP clients (Cursor, Claude Code, ...):',
      `  URL     ${mcp}`,
      `  Header  Authorization: Bearer <${ENV.mcpToken} from ${paths.bridgeEnv}>`,
      '',
      'Hermes (conversational turns) is not configured by setup:',
      `  add HERMES_API_SERVER_KEY=<your Hermes gateway key> (and HERMES_BASE_URL if not http://127.0.0.1:8642)`,
      `  to ${paths.coreEnv}, then: botmancers stop && botmancers start --daemon`,
      '',
      'Coding-agent runs are not configured by setup:',
      '  install the provider CLIs you need (claude, codex, cursor, muse) and sign each one in,',
      '  then register Agents against their runtime connections in Botmancers.',
      '',
      'Check everything with: botmancers doctor',
    ];
    return { created, lines };
  } catch (error) {
    const code = (error as { code?: string }).code;
    if (code === 'EACCES' || code === 'EPERM' || code === 'EROFS' || code === 'ENOTDIR' || code === 'EEXIST') {
      throw new SetupError(`cannot write BOTMANCERS_HOME ${paths.home} (${code}). Choose a writable directory with BOTMANCERS_HOME or fix its permissions.`);
    }
    throw error;
  }
}
